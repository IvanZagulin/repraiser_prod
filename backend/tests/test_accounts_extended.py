class TestAccountRead:
    def test_list_empty(self, client):
        r = client.get("/api/accounts")
        assert r.status_code == 200
        body = r.json()
        assert "accounts" in body
        assert "total" in body

    def test_list_own_accounts(self, client, test_account):
        r = client.get("/api/accounts")
        assert r.status_code == 200
        ids = [a["id"] for a in r.json()["accounts"]]
        assert test_account.id in ids

    def test_get_by_id(self, client, test_account):
        r = client.get(f"/api/accounts/{test_account.id}")
        assert r.status_code == 200
        assert r.json()["id"] == test_account.id

    def test_idor_get_other_account(self, client, db_session):
        """Cannot read another user's account."""
        from app.models.user import User
        from app.api.auth import hash_password
        other = User(email="idor_read@test.com", password_hash=hash_password("P123!"),
                     is_active=True, is_verified=True, token_version=1,
                     verification_attempts=0, reset_attempts=0)
        db_session.add(other); db_session.commit()
        acc = Account(user_id=other.id, name="Hidden", wb_api_token="secret",
                      is_active=True)
        db_session.add(acc); db_session.commit()

        r = client.get(f"/api/accounts/{acc.id}")
        assert r.status_code == 404  # must NOT expose other user's account

        db_session.delete(acc); db_session.delete(other); db_session.commit()

    def test_get_nonexistent_account(self, client):
        r = client.get("/api/accounts/999999")
        assert r.status_code == 404

    def test_accounts_isolated_between_users(self, client, db_session):
        from app.models.user import User
        from app.api.auth import hash_password
        other = User(email="iso_acc@test.com", password_hash=hash_password("P123!"),
                     is_active=True, is_verified=True, token_version=1,
                     verification_attempts=0, reset_attempts=0)
        db_session.add(other); db_session.commit()
        acc = Account(user_id=other.id, name="Foreign Shop", wb_api_token="x",
                      is_active=True)
        db_session.add(acc); db_session.commit()

        r = client.get("/api/accounts")
        names = [a["name"] for a in r.json()["accounts"]]
        assert "Foreign Shop" not in names

        db_session.delete(acc); db_session.delete(other); db_session.commit()


