class TestAccountCreate:
    def test_create_valid(self, client):
        r = client.post("/api/accounts", json={
            "name": "My WB Shop", "wb_api_token": "eyJ.fake.token"})
        assert r.status_code == 201
        body = r.json()
        assert body["name"] == "My WB Shop"
        assert "id" in body
        # Token must NOT be in response (security!)
        assert "wb_api_token" not in body or body.get("wb_api_token") is None

    def test_create_requires_auth(self, anon_client):
        r = anon_client.post("/api/accounts", json={
            "name": "Shop", "wb_api_token": "tok"})
        assert r.status_code == 401

    def test_create_empty_name(self, client):
        r = client.post("/api/accounts", json={"name": "", "wb_api_token": "tok"})
        assert r.status_code == 422

    def test_create_missing_token(self, client):
        r = client.post("/api/accounts", json={"name": "Shop"})
        assert r.status_code == 422


